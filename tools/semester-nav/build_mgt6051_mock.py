#!/usr/bin/env python3
"""Builds assets/mgt6051-mock-test-data.js (combined pool from the weekly quiz files) and
mgt6051-mock-test.html. Reuses the existing assets/mktg-mocktest.js engine (it reads the globals
MKTG_MOCK_POOL / MKTG_MOCK_LABELS, which this data file defines). Run from the site folder."""
import os, re, json, subprocess, sys
ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else '.')
A = os.path.join(ROOT, 'assets')
PAGES = [('mgt6051-wk1', 'Wk 1'), ('mgt6051-wk2', 'Wk 2'), ('mgt6051-wk3', 'Wk 3'), ('mgt6051-wk4', 'Wk 4'), ('mgt6051-wk5', 'Wk 5 review')]
NODE = r'''
const fs=require('fs'),vm=require('vm');
const [qf,ff]=process.argv.slice(1);
const c={};vm.createContext(c);
vm.runInContext(fs.readFileSync(qf,'utf8').replace(/\bconst\b/g,'var'),c);
vm.runInContext(fs.readFileSync(ff,'utf8').replace(/\bconst\b/g,'var'),c);
console.log(JSON.stringify({q:c.QUIZ_QUESTIONS,l:c.SOURCE_LABELS}));
'''
pool, labels = [], {}
for page, tag in PAGES:
    qf, ff = (os.path.join(A, f'{page}-quiz-data.js'), os.path.join(A, f'{page}-flashcards-data.js'))
    if not (os.path.exists(qf) and os.path.exists(ff)):
        print('skip', page); continue
    out = subprocess.run(['node', '-e', NODE, qf, ff], capture_output=True, text=True, check=True).stdout
    d = json.loads(out)
    pre = page.replace('mgt6051-', '') + '_'
    for q in d['q']:
        q = dict(q); q['source'] = pre + q['source']; pool.append(q)
    for k, v in d['l'].items():
        labels[pre + k] = f'{tag} · {v}'
    for q in pool:
        labels.setdefault(q['source'], q['source'])
js = ('// Combined MGT 6051 (Part 1) mock-test pool, generated by build_mgt6051_mock.py from the weekly quiz files.\n'
      '// Uses the global names the shared mock-test engine (mktg-mocktest.js) looks for.\n'
      'const MKTG_MOCK_POOL = ' + json.dumps(pool, indent=1, ensure_ascii=False) + ';\n\n'
      'const MKTG_MOCK_LABELS = ' + json.dumps(labels, indent=1, ensure_ascii=False) + ';\n')
open(os.path.join(A, 'mgt6051-mock-test-data.js'), 'w', encoding='utf-8').write(js)

s = open(os.path.join(ROOT, 'mktg-mock-test.html'), encoding='utf-8').read()
s = s.replace('<body class="theme-mktg">', '<body>')
s = re.sub(r'<title>.*?</title>', '<title>MGT 6051 Mock Test — PMBA Field Guide</title>', s, flags=re.S)
s = re.sub(r'<meta name="description" content=".*?">', '<meta name="description" content="A randomized multiple-choice mock test built from the MGT 6051 Part 1 weekly pages (values, leadership, hiring, onboarding and culture), auto-graded with explanations.">', s, flags=re.S)
s = s.replace('MKTG 6090 &#x00b7; Mock Test', 'MGT 6051 &#x00b7; Mock Test')
s = re.sub(r'(<p class="lede"[^>]*>).*?(</p>)', r'\1Pick how many questions you want, and the test draws that many at random from the MGT 6051 Part 1 bank: <strong>Weeks 1 to 4 plus the midterm review</strong> &mdash; Christensen, Ingram &amp; Choi, Jordan et al., David, Tomaskovic-Devey &amp; Orellana, the Kouzes &amp; Posner summaries and the professor&rsquo;s slides. Built to rehearse for the 12/1 midterm.\2', s, count=1, flags=re.S)
s = re.sub(r'(<p class="text-soft">)Each option pulls.*?(</p>)', r'\1Each option pulls a fresh random subset of the combined bank.\2', s, count=1, flags=re.S)
s = re.sub(r'<div class="callout">.*?</div>', '<div class="callout">This draws from the combined MGT 6051 Part 1 question bank &mdash; the same questions behind the quiz on each weekly page (<a href="mgt6051-wk1.html#quiz">Wk 1</a>, <a href="mgt6051-wk2.html#quiz">Wk 2</a>, <a href="mgt6051-wk3.html#quiz">Wk 3</a>, <a href="mgt6051-wk4.html#quiz">Wk 4</a>, <a href="mgt6051-wk5.html#quiz">Wk 5</a>).</div>', s, count=1, flags=re.S)
s = re.sub(r'<footer class="footer">.*?</footer>', '<footer class="footer">\n  <div class="wrap">\n    <p>MGT 6051 &#x2014; Managing and Leading in Organizations, University of Utah PMBA. Question bank generated from the weekly study pages; Part 2 material will be added in the spring.</p>\n  </div>\n</footer>', s, count=1, flags=re.S)
s = s.replace('mktg-mock-test-data.js', 'mgt6051-mock-test-data.js').replace('crimson', '')
s = s.replace('class="btn "', 'class="btn"')
assert 'MKTG' not in re.sub(r'MKTG_MOCK|mktg-mocktest', '', s.split('</header>',1)[1]), 'leftover MKTG text'
open(os.path.join(ROOT, 'mgt6051-mock-test.html'), 'w', encoding='utf-8').write(s)
print('pool', len(pool), 'labels', len(labels))
