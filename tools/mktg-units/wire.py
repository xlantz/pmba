#!/usr/bin/env python3
"""Wire the built MKTG unit pages into the rest of the site. Idempotent.

    python tools/mktg-units/wire.py

1. Nav (every page): the MKTG 6090 dropdown lists the built units, then any chapter page not yet
   fully covered by a built unit, then the mock test. Nav links to in-page anchors that do not
   exist on that page (e.g. "Quiz" on the mock-test page) are dropped.
2. Home page: the MKTG cards become one card per built unit, plus the original card of any chapter
   not yet covered, ahead of the mock-test card (managed between MKTG-UNITS markers).
3. Mock test: authored unit questions (slides, case prompts, Ch 4/12/13) are appended to the pool
   with their labels (managed between MKTG-UNITS markers at the end of mktg-mock-test-data.js).

The original chapter nav links and home cards are captured once into chapter-links.json so they can
be restored for chapters that no unit covers yet.
"""
import glob, html, json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build import SITE, UNITS, load_unit, read, write  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
STORE = os.path.join(HERE, 'chapter-links.json')
BEGIN, END = '<!-- MKTG-UNITS:BEGIN (generated by tools/mktg-units/wire.py) -->', '<!-- MKTG-UNITS:END -->'
JBEGIN, JEND = '/* MKTG-UNITS:BEGIN (generated by tools/mktg-units/wire.py) */', '/* MKTG-UNITS:END */'

units = {}
for d in sorted(glob.glob(os.path.join(UNITS, 'u*')), key=lambda p: int(re.search(r'u(\d+)$', p).group(1))):
    n = int(re.search(r'u(\d+)$', d).group(1))
    if os.path.exists(os.path.join(SITE, f'mktg-unit{n}.html')):
        units[n] = load_unit(n)
# A chapter used by any built unit (even in part, like Ch 14 in Unit 5) is reached through that unit's
# chapter-reference box, so it no longer gets its own menu link or home card.
covered = {p['chapter'] for u in units.values() for p in u['META']['parts'] if 'chapter' in p}

# ---------------------------------------------------------------- capture originals once
store = json.loads(read(STORE)) if os.path.exists(STORE) else {'nav': {}, 'cards': {}}
idx = read(os.path.join(SITE, 'index.html'))
for m in re.finditer(r'<a href="mktg(\d+)\.html">(Ch [^<]*)</a>', idx):
    store['nav'].setdefault(m.group(1), m.group(2))
CARD = re.compile(r'[ \t]*<a class="unit-card" href="mktg(\d+)\.html">.*?</a>\n?', re.S)
for m in CARD.finditer(idx):
    store['cards'].setdefault(m.group(1), m.group(0).strip())
write(STORE, json.dumps(store, indent=2, ensure_ascii=False) + '\n')

uncovered = sorted((int(c) for c in store['nav'] if int(c) not in covered))


# ---------------------------------------------------------------- 1. nav
def mktg_menu(indent):
    items = [f'<a href="mktg-unit{n}.html">Unit {n} &mdash; {html.escape(u["META"]["nav"])}</a>' for n, u in units.items()]
    items += [f'<a href="mktg{c}.html">{store["nav"][str(c)]}</a>' for c in uncovered]
    items.append('<a href="mktg-mock-test.html">MKTG 6090 Mock Test</a>')
    return ''.join(f'\n{indent}{i}' for i in items) + '\n' + indent[:-2]


label_href = 'mktg-unit1.html' if 1 in units else 'mktg1.html'
changed = []
for p in sorted(glob.glob(os.path.join(SITE, '*.html'))):
    s = orig = read(p)
    a = s.find('<nav class="topnav">')
    if a < 0:
        continue
    b = s.index('</nav>', a)
    nav = s[a:b]
    lab = re.search(r'<a href="[^"]*" class="nav-dropdown-label( active)?">MKTG 6090</a>', nav)
    if lab:
        nav = nav.replace(lab.group(0), f'<a href="{label_href}" class="nav-dropdown-label{lab.group(1) or ""}">MKTG 6090</a>')
        start = nav.index('<div class="nav-dropdown-menu-inner">', lab.end()) + len('<div class="nav-dropdown-menu-inner">')
        end = nav.index('</div>', start)
        indent = re.search(r'\n([ \t]*)<a', nav[start:end]).group(1)
        nav = nav[:start] + mktg_menu(indent) + nav[end:]
    nav = re.sub(r'\n[ \t]*<a href="#([^"]+)"[^>]*>[^<]*</a>',
                 lambda m: m.group(0) if f'id="{m.group(1)}"' in s else '', nav)
    s = s[:a] + nav + s[b:]
    if s != orig and write(p, s):
        changed.append(os.path.basename(p))

# ---------------------------------------------------------------- 2. home cards
idx = read(os.path.join(SITE, 'index.html'))
cards = []
for n, u in units.items():
    M = u['META']
    tags = ''.join(f'\n          <span class="tag">{html.escape(t)}</span>' for t in M['card']['tags'])
    cards.append(f'''      <a class="unit-card" href="mktg-unit{n}.html">
        <span class="eyebrow">MKTG 6090 &#x00b7; Unit {n} &#x00b7; Week {M["week"]}</span>
        <h3>{html.escape(M["title_plain"])}</h3>
        <p>{M["card"]["blurb"]}</p>
        <div class="tag-row">{tags}
        </div>
      </a>''')
cards += ['      ' + store['cards'][str(c)].strip() for c in uncovered if store['cards'].get(str(c))]
block = BEGIN + '\n' + '\n\n'.join(cards) + '\n      ' + END
if BEGIN in idx:
    idx2 = idx[:idx.index(BEGIN)] + block + idx[idx.index(END) + len(END):]
else:
    # first run: remove the chapter cards and put the managed block where the first one was
    first = CARD.search(idx).start()
    rest = CARD.sub('', idx[first:])
    idx2 = idx[:first] + '      ' + block + '\n\n' + rest.lstrip('\n')
idx2 = re.sub(r'(<a class="unit-card" href="mktg-mock-test.html">.*?<p>)A random draw of multiple-choice questions pulled from .*?\.( Submit once)',
              lambda m: m.group(1) + 'A random draw of multiple-choice questions pulled from every MKTG chapter quiz plus the '
              'weekly unit pages&rsquo; slide and case questions.' + m.group(2), idx2, count=1, flags=re.S)
if write(os.path.join(SITE, 'index.html'), idx2) and 'index.html' not in changed:
    changed.append('index.html')

# ---------------------------------------------------------------- 3. mock test
mp = os.path.join(SITE, 'assets/mktg-mock-test-data.js')
mt = read(mp)
qs, labels = [], {}
for n, u in units.items():
    for k, prompt, options, ci, expl in u['QUIZ']:
        qs.append(dict(source=k, prompt=prompt, options=options, correctIndex=ci,
                       correctFeedback='Correct.', incorrectFeedback='Not quite.', explanation=expl))
        labels[k] = u['LABELS'][k]
managed = (JBEGIN + '\n// Unit slide, case-prompt and Ch 4/12/13 questions from the MKTG unit pages.\n'
           'const MKTG_UNIT_QUESTIONS = ' + json.dumps(qs, indent=2, ensure_ascii=False) + ';\n'
           'MKTG_MOCK_POOL.push(...MKTG_UNIT_QUESTIONS);\n'
           'Object.assign(MKTG_MOCK_LABELS, ' + json.dumps(labels, indent=2, ensure_ascii=False) + ');\n' + JEND + '\n')
mt2 = (mt[:mt.index(JBEGIN)] + managed + mt[mt.index(JEND) + len(JEND) + 1:]) if JBEGIN in mt else mt.rstrip('\n') + '\n\n' + managed
if write(mp, mt2):
    changed.append('assets/mktg-mock-test-data.js')

# ---------------------------------------------------------------- 4. mock-test page wording
def series(xs):
    xs = [str(x) for x in xs]
    return xs[0] if len(xs) == 1 else ', '.join(xs[:-1]) + ' and ' + xs[-1]


chapter_pages = sorted(int(c) for c in store['nav'])
authored_ch = sorted({int(m.group(1)) for u in units.values() for k in u['LABELS'] for m in [re.match(r'c(\d+)_', k)] if m})
unit_nums = list(units)
unit_range = f'Units {unit_nums[0]}&ndash;{unit_nums[-1]}' if unit_nums == list(range(unit_nums[0], unit_nums[-1] + 1)) else 'Units ' + series(unit_nums)
pp = os.path.join(SITE, 'mktg-mock-test.html')
page = orig = read(pp)
page = re.sub(r'(<meta name="description" content=")[^"]*(">)',
              lambda m: m.group(1) + 'A randomized multiple-choice mock test built from every MKTG 6090 chapter quiz and the '
              'weekly unit pages&#x2019; slide and case questions, auto-graded with explanations.' + m.group(2), page, count=1)
page = re.sub(r'(<p class="lede"[^>]*>Pick how many questions you want, ).*?( Submit once)',
              lambda m: m.group(1) + 'and the test draws that many at random from the full MKTG 6090 question bank: the quiz on '
              f'every chapter page (Ch {series(chapter_pages)}), the Chapter {series(authored_ch)} sections on the unit pages, and '
              f'the questions on the professor&rsquo;s slides and case prompts from {unit_range}.' + m.group(2), page, count=1, flags=re.S)
chap_links = ', '.join(f'<a href="mktg{c}.html#quiz">Ch {c}</a>' for c in chapter_pages)
unit_links = ', '.join(f'<a href="mktg-unit{n}.html#quiz">Unit {n}</a>' for n in unit_nums)
page = re.sub(r'This draws from .*? &mdash; the difference is',
              lambda m: f'This draws from the quiz bank on each chapter page ({chap_links}) plus the slide, case-prompt and '
              f'Chapter {series(authored_ch)} questions from the weekly unit pages ({unit_links}) &mdash; the difference is',
              page, count=1, flags=re.S)
page = re.sub(r'(<footer class="footer">\s*<div class="wrap">\s*<p>).*?(</p>)',
              lambda m: m.group(1) + 'MKTG 6090 &#x2014; Marketing Management, University of Utah PMBA. Question bank built from the '
              'chapter pages and the weekly unit pages (Kotler/Keller/Chernev, <em>Marketing Management</em>, 17th ed., and the '
              'professor&rsquo;s slides); it grows as new units and slides are added.' + m.group(2), page, count=1, flags=re.S)
if page != orig and write(pp, page):
    changed.append('mktg-mock-test.html')

print(f'units: {list(units)}; chapters still listed on their own: {uncovered}; mock-test unit questions: {len(qs)}')
print('changed: ' + (', '.join(changed) if changed else 'nothing'))
